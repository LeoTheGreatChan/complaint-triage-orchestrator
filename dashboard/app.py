def main():
    inject_brand_css()
    log = load_pipeline_log()

    st.markdown("## Complaint Triage Orchestrator")
    st.markdown(
        '<p class="section-caption">Real CFPB complaint data + real federal regulation text + a disclosed '
        "synthetic CRM layer, triaged by four conditional-tool-use agents behind a deterministic escalation "
        "gate.</p>",
        unsafe_allow_html=True,
    )

    if log is None:
        st.warning(
            f"No pipeline data found at `{DATA_PATH}`. Run `node scripts/export_dashboard_data.mjs` "
            "from the repo root first."
        )
        render_disclosure_banner()
        return

    records = log["records"]

    tab_overview, tab_technical = st.tabs(["Overview", "Technical detail"])

    with tab_overview:
        if len(records) < 10:
            st.markdown(
                f'<p class="section-caption"><strong>{len(records)} ticket(s) processed to date</strong> — '
                "this build's four agents are mock-first (spec Phase 3): only the three Section 6 fixture "
                "tickets have a genuine pipeline decision. Real live-ticket volume arrives after Phase 7's "
                "Claude API swap; charts below reflect exactly what's real today, not a padded sample.</p>",
                unsafe_allow_html=True,
            )

        cols = st.columns(5)
        hs_val, hs_sub = kpi_hours_saved()
        render_kpi_card(cols[0], "Hours saved / ticket", hs_val, hs_sub)
        ca_val, ca_sub = kpi_citation_accuracy(records)
        render_kpi_card(cols[1], "Citation accuracy", ca_val, ca_sub)
        sla_val, sla_sub = kpi_sla_compliance()
        render_kpi_card(cols[2], "SLA compliance", sla_val, sla_sub)
        ea_val, ea_sub = kpi_escalation_agreement(records)
        render_kpi_card(cols[3], "Escalation agreement", ea_val, ea_sub)
        cat_val, cat_sub = kpi_category_agreement(records)
        render_kpi_card(cols[4], "Category agreement", cat_val, cat_sub)

        st.markdown("<br>", unsafe_allow_html=True)
        left, right = st.columns(2)
        with left:
            st.plotly_chart(chart_decision_breakdown(records), use_container_width=True)
        with right:
            st.plotly_chart(chart_category_breakdown(records), use_container_width=True)

        st.markdown("#### Queue: drafts awaiting human review")
        render_queue_table(records)

    with tab_technical:
        st.markdown(
            '<p class="section-caption">Agent-level detail, kept separate from the business-facing view '
            "(spec Section 10).</p>",
            unsafe_allow_html=True,
        )
        left, right = st.columns(2)
        with left:
            st.plotly_chart(chart_confidence_distribution(records), use_container_width=True)
        with right:
            st.plotly_chart(chart_tool_use_frequency(records), use_container_width=True)

        st.markdown("#### Raw pipeline log")
        st.dataframe(pd.json_normalize(records), use_container_width=True, height=300)

        with st.expander("Other required disclosures (spec Section 14)"):
            st.markdown(
                "- Real, live, government-verified complaints against named real companies — "
                "independent portfolio analysis, not affiliated with or endorsed by any company named in the data.\n"
                "- Escalation-agreement and similar outcome-comparison metrics are directional signals, "
                "not certified accuracy.\n"
                "- Policy citations reference real federal regulation; this is a technical demonstration, "
                "not legal advice."
            )

    render_disclosure_banner()


def render_disclosure_banner():
    st.markdown(
        '<div class="disclosure-banner">Customer/account records shown here are <strong>synthetic</strong> '
        "(spec Section 3c) — generated to demonstrate the pipeline, not real customer data. "
        "servicemember_flag and special_population_flag carry forward CFPB's own real tags field where present; "
        "everything else in the CRM record is synthetic.</div>",
        unsafe_allow_html=True,
    )


if __name__ == "__main__":
    main()
