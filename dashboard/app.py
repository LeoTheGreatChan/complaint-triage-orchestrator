def plotly_brand_layout(fig: go.Figure, title: str) -> go.Figure:
    fig.update_layout(
        title=dict(text=title, font=dict(family="Manrope, sans-serif", size=14, color=NAVY)),
        font=dict(family="Inter, sans-serif", size=12, color=SLATE),
        plot_bgcolor=WHITE,
        paper_bgcolor=WHITE,
        margin=dict(l=10, r=10, t=40, b=10),
        legend=dict(font=dict(family="Inter, sans-serif", size=11)),
    )
    fig.update_xaxes(showline=True, linecolor=LIGHT_GREY, gridcolor=LIGHT_GREY)
    fig.update_yaxes(showline=True, linecolor=LIGHT_GREY, gridcolor=LIGHT_GREY)
    return fig


