def chart_decision_breakdown(records):
    counts = {"Escalated to human": 0, "Auto-resolved": 0}
    for r in records:
        if r["decision"] == "ESCALATE_TO_HUMAN":
            counts["Escalated to human"] += 1
        else:
            counts["Auto-resolved"] += 1
    fig = go.Figure(
        go.Bar(
            x=list(counts.keys()),
            y=list(counts.values()),
            marker_color=[NAVY, "#94A3B8"],
            text=list(counts.values()),
            textposition="outside",
            width=0.5,
        )
    )
    fig.update_layout(yaxis=dict(dtick=1))
    return plotly_brand_layout(fig, "Escalate vs. auto-resolve")


def chart_category_breakdown(records):
    counts = {}
    for r in records:
        counts[r["product"]] = counts.get(r["product"], 0) + 1
    fig = go.Figure(
        go.Pie(
            labels=list(counts.keys()),
            values=list(counts.values()),
            marker=dict(colors=CHART_SERIES),
            hole=0.55,
            textfont=dict(family="Inter, sans-serif"),
        )
    )
    return plotly_brand_layout(fig, "Product category breakdown")


def chart_confidence_distribution(records):
    fig = go.Figure()
    for i, agent_key in enumerate(["agent1", "agent4"]):
        label = "Agent 1 (Classification)" if agent_key == "agent1" else "Agent 4 (QA/scoring)"
        values, labels = [], []
        for r in records:
            out = r["agents"][agent_key]["output"] or {}
            conf = out.get("confidence")
            if conf is None and "issues" in out:
                # Ticket C's multi-issue schema: use the primary issue's confidence.
                primary = next((i for i in out["issues"] if i["issue"] == out.get("primary_issue")), None)
                conf = primary["confidence"] if primary else None
            if conf is not None:
                values.append(conf)
                labels.append(r["complaint_id"])
        fig.add_trace(go.Bar(name=label, x=labels, y=values, marker_color=CHART_SERIES[i]))
    # complaint_id ("9999970") reads as numeric to Plotly's default axis-type
    # inference, which formats it with an SI suffix ("9.99997M") -- force a
    # categorical axis so it prints as the literal ID.
    fig.update_layout(barmode="group", yaxis=dict(range=[0, 1], title="confidence"), xaxis=dict(type="category"))
    return plotly_brand_layout(fig, "Agent confidence by ticket")


def chart_tool_use_frequency(records):
    tool_labels = {
        "agent1": "Agent 1: taxonomy lookup",
        "agent2_regulation": "Agent 2: regulation index (always)",
        "agent2_crm": "Agent 2: broader CRM lookup",
        "agent3": "Agent 3: exact clause fetch",
        "agent4": "Agent 4: re-verify",
    }
    counts = {k: 0 for k in tool_labels}
    for r in records:
        a = r["agents"]
        if a["agent1"]["tool_used"]:
            counts["agent1"] += 1
        counts["agent2_regulation"] += 1  # always runs, spec Section 6
        if a["agent2"]["broader_crm_lookup_used"]:
            counts["agent2_crm"] += 1
        if a["agent3"]["tool_used"]:
            counts["agent3"] += 1
        if a["agent4"]["tool_used"]:
            counts["agent4"] += 1
    n = len(records)
    fig = go.Figure(
        go.Bar(
            y=[tool_labels[k] for k in tool_labels],
            x=[counts[k] for k in tool_labels],
            orientation="h",
            marker_color=NAVY,
            text=[f"{counts[k]}/{n}" for k in tool_labels],
            textposition="outside",
        )
    )
    fig.update_layout(xaxis=dict(range=[0, n + 0.5], dtick=1), margin=dict(l=190))
    return plotly_brand_layout(fig, "Tool-use frequency (of tickets processed)")


# ---------------------------------------------------------------------------
# Queue table -- drafts awaiting human review.
# ---------------------------------------------------------------------------
def render_queue_table(records):
    escalated = [r for r in records if r["decision"] == "ESCALATE_TO_HUMAN"]
    if not escalated:
        st.markdown('<p class="section-caption">No tickets currently awaiting human review.</p>', unsafe_allow_html=True)
        return

    rows = []
    for r in escalated:
        draft = (r["agents"]["agent3"]["output"] or {}).get("draft", "")
        draft_preview = (draft[:110] + "…") if len(draft) > 110 else draft
        reason = (r["agents"]["agent4"]["output"] or {}).get("reason", "")
        confidence = (r["agents"]["agent4"]["output"] or {}).get("confidence")
        rows.append(
            f"""
            <tr>
                <td class="mono">{r['complaint_id']}</td>
                <td>{r['company']}</td>
                <td>{r['issue']}</td>
                <td>{draft_preview}</td>
                <td>{confidence:.2f}</td>
                <td>{reason}</td>
            </tr>
            """
        )

    md_html(
        f"""
        <table class="queue-table">
            <thead>
                <tr>
                    <th>Complaint ID</th><th>Company</th><th>Issue</th>
                    <th>Draft (preview)</th><th>QA confidence</th><th>Escalation reason</th>
                </tr>
            </thead>
            <tbody>{''.join(rows)}</tbody>
        </table>
        """
    )


