def kpi_citation_accuracy(records):
    # Real, computed: for every ticket where Agent 3 cited a regulation,
    # did the exact-clause-fetch tool actually resolve it against the
    # cached, real regulation corpus? This is QA-verified, not
    # self-reported -- Agent 3's and Agent 4's tool_result.found both come
    # from independent real lookups (see README's regulation-search
    # limitation note for the ceiling this implies).
    cited = [r for r in records if r["agents"]["agent3"]["tool_used"]]
    if not cited:
        return None, "No drafts cited a regulation yet"
    correct = sum(1 for r in cited if (r["agents"]["agent3"]["tool_result"] or {}).get("found"))
    pct = round(100 * correct / len(cited))
    return pct, f"{correct}/{len(cited)} cited drafts, QA-verified against real regulation text"


def kpi_escalation_agreement(records):
    # Real, computed -- and expected to read low here. See README/spec
    # Section 8: CFPB's own outcome category is a coarse administrative
    # label, not a severity judgment, so low agreement on this fixture set
    # is a demonstration of the metric's own honest limits, not a pipeline
    # defect. Never report this as accuracy.
    with_gt = [r for r in records if r.get("ground_truth")]
    if not with_gt:
        return None, "No ground-truth comparisons yet"
    agree = sum(1 for r in with_gt if r["ground_truth"]["agrees_with_ground_truth"])
    pct = round(100 * agree / len(with_gt))
    return pct, f"{agree}/{len(with_gt)} agree with CFPB's outcome fields — directional signal, not accuracy (Section 8)"


def kpi_category_agreement(records):
    # Real, computed: does Agent 1's classified issue match what the
    # consumer actually filed with CFPB, at either the issue or sub-issue
    # level (Ticket C's classification lands at the sub-issue level, since
    # that's the substantive category for that compound ticket -- see
    # spec Section 6).
    if not records:
        return None, "No classifications yet"
    matches = 0
    for r in records:
        out = r["agents"]["agent1"]["output"] or {}
        classified = out.get("primary_issue") or out.get("issue")
        if classified and classified in (r.get("issue"), r.get("sub_issue")):
            matches += 1
    pct = round(100 * matches / len(records))
    return pct, f"{matches}/{len(records)} match CFPB's own filed product/issue category"


