def main():
    inject_brand_css()
    log = load_pipeline_log()

    st.markdown("## Complaint Triage Orchestrator")
    st.markdown(
        '<p class="section-caption">Real CFPB complaint data + real federal regulation text + a disclosed '
        "synthetic CRM layer, triaged by four conditional-tool-use agents behind a deterministic escalation "
        "gate.</p>",
        unsafe_allow_html=True,
    )

    if log is None:
        st.warning(
            f"No pipeline data found at `{DATA_PATH}`. Run `node scripts/export_dashboard_data.mjs` "
            "from the repo root first."
        )
        render_disclosure_banner()
        return

    records = log["records"]
    awaiting_records = log.get("awaiting_records", [])

    # Category filter: single source of truth for both tabs. Read directly
    # from session_state rather than the st.multiselect(...) call itself,
    # since that widget is declared further down (inside tab_overview) but
    # this value is also needed here, before st.tabs() runs, for the
    # Technical detail tab's dynamic label -- a keyed widget's session_state
    # slot is already updated by the time the script re-runs, regardless of
    # where in the script the widget itself is declared.
    categories = []
    seen_categories = set()
    for r in records:
        p = r["product"]
        if p not in seen_categories:
            seen_categories.add(p)
            categories.append(p)
    st.session_state.setdefault("category_filter_multiselect", [])
    selected_categories = set(st.session_state.category_filter_multiselect)
    filtered_records = [r for r in records if r["product"] in selected_categories] if selected_categories else records

    technical_label = "Technical detail"
    if selected_categories:
        # Stable order matching the chart/legend/dropdown (categories'
        # own insertion order), not sorted() or set iteration order.
        technical_label = f"Technical detail ({', '.join(c for c in categories if c in selected_categories)})"

    # Seeds the queue-view toggle from a `?queue_view=...` URL query param --
    # must happen before st.segmented_control(key="queue_view") instantiates
    # below, since a keyed widget's session_state entry, once set, wins over
    # `default` on every later rerun. Only applied once per session (real
    # navigations from the bar-jump links below create a fresh session
    # anyway); a manual toggle click after that always takes priority.
    scroll_to_queue = False
    if "queue_view" not in st.session_state:
        requested_view = st.query_params.get("queue_view")
        if requested_view in ("Escalated to human", "Auto-resolved"):
            st.session_state["queue_view"] = requested_view
            scroll_to_queue = True
        else:
            # Same value segmented_control's own `default` would have used --
            # set directly instead of passing `default=` alongside a keyed
            # widget that Session State already governs, which Streamlit
            # warns is a conflicting/undefined combination.
            st.session_state["queue_view"] = "Escalated to human"

    tab_overview, tab_technical = st.tabs(["Overview", technical_label])

    with tab_overview:
        if len(records) < 50:
            st.markdown(
                f'<p class="section-caption"><strong>{len(records)} ticket(s) processed to date</strong> — '
                "this build's four agents are mock-first (spec Phase 3): only tickets with hand-verified "
                "fixture data (spec Section 6's original three, plus any added since) have a genuine "
                "pipeline decision. Real live-ticket volume arrives after Phase 7's Claude API swap; charts "
                "below reflect exactly what's real today, not a padded sample.</p>",
                unsafe_allow_html=True,
            )

        render_awaiting_table(awaiting_records, len(filtered_records))

        cols = st.columns(5)
        hs_val, hs_sub = kpi_hours_saved()
        render_kpi_card(cols[0], "Hours saved / ticket", hs_val, hs_sub)
        ca_val, ca_sub = kpi_citation_accuracy(filtered_records)
        render_kpi_card(cols[1], "Citation accuracy", ca_val, ca_sub)
        sla_val, sla_sub = kpi_sla_compliance()
        render_kpi_card(cols[2], "SLA compliance", sla_val, sla_sub)
        ea_val, ea_sub = kpi_escalation_agreement(filtered_records)
        render_kpi_card(cols[3], "Escalation agreement", ea_val, ea_sub)
        cat_val, cat_sub = kpi_category_agreement(filtered_records)
        render_kpi_card(cols[4], "Category agreement", cat_val, cat_sub)

        st.markdown("<br>", unsafe_allow_html=True)

        # Category filter (categories/selected_categories/filtered_records
        # computed earlier, before st.tabs()). Native Plotly click-to-select
        # on the donut was tried and ruled out first: 0/5 real slice clicks
        # registered a selection, and legend clicks are pure client-side
        # trace-visibility toggles that never reach Streamlit's selection
        # state at all -- worse than the bar chart's already-flaky results.
        # This multiselect is a real, guaranteed-to-register widget instead.
        #
        # Positioned above both charts, not tucked under the donut: this is
        # the primary filter (pick a category), with the escalate/auto-
        # resolve bars beside the donut as the secondary filter within it --
        # top-to-bottom placement matches that selection order.
        st.multiselect(
            "Filter by product category", options=categories, key="category_filter_multiselect",
            placeholder="All categories shown — select to filter",
        )

        left, right = st.columns(2)
        with left:
            # Deliberately built from the unfiltered `records`, with only the
            # selected slice(s) at full color and the rest dimmed -- this
            # chart IS the filter control, so it shows the whole picture with
            # the current selection highlighted, not a recomputed subset.
            st.plotly_chart(chart_category_breakdown(records, selected_categories), width='stretch')
        with right:
            # A Plotly bar-click -> table-jump interaction was tried first via
            # st.plotly_chart(..., on_select="rerun") and dropped after it
            # proved flaky under real clicks (re-verified live: sometimes a
            # click's selection state didn't land until the NEXT click,
            # sometimes it silently reset to empty -- inconsistent is worse
            # than a clean failure, and the flakiness is in Streamlit's
            # Python-JS selection bridge, not Plotly's own rendering.
            # A plain HTML <a href="?queue_view=...#queue-section"> overlay,
            # positioned over each bar with a keyed st.container for CSS
            # scoping, sidesteps that bridge entirely -- it's a real browser
            # navigation with a query param + anchor, not a Streamlit rerun
            # event. `main()` seeds st.session_state["queue_view"] from
            # st.query_params before the segmented_control below is
            # instantiated, so this and the manual toggle both drive the same
            # single source of truth.
            with st.container(key="decision_chart_wrap"):
                st.plotly_chart(chart_decision_breakdown(filtered_records), width='stretch')
                st.markdown(
                    """
                    <style>
                    .st-key-decision_chart_wrap { position: relative; }
                    /* Streamlit wraps every element (including this markdown
                       call) in its own position:relative, height:0 container
                       -- that becomes the nearest positioned ancestor and
                       steals the containing-block role before top/bottom %
                       can resolve against the wrapper above. Neutralize it. */
                    .st-key-decision_chart_wrap .stElementContainer { position: static; }
                    .st-key-decision_chart_wrap .bar-jump-link {
                        position: absolute; top: 14%; bottom: 10%;
                        border-radius: 6px; cursor: pointer;
                    }
                    .st-key-decision_chart_wrap .bar-jump-link:hover { background: rgba(21, 62, 117, 0.08); }
                    .st-key-decision_chart_wrap .bar-jump-left { left: 2%; width: 44%; }
                    .st-key-decision_chart_wrap .bar-jump-right { right: 2%; width: 44%; }
                    </style>
                    <a class="bar-jump-link bar-jump-left" title="Jump to: drafts awaiting human review"
                       href="?queue_view=Escalated+to+human#queue-section"></a>
                    <a class="bar-jump-link bar-jump-right" title="Jump to: auto-resolved tickets"
                       href="?queue_view=Auto-resolved#queue-section"></a>
                    """,
                    unsafe_allow_html=True,
                )

        st.markdown('<div id="queue-section"></div>', unsafe_allow_html=True)
        if scroll_to_queue:
            # st.markdown-injected <script> tags don't execute in Streamlit
            # (HTML is set via innerHTML, not parsed as live markup) --
            # components.v1.html runs in a real iframe, where they do. The
            # anchor in the bar-jump links' href can't do this alone: the
            # browser tries to jump to #queue-section on initial page load,
            # before Streamlit has finished rendering that element, so the
            # native jump silently misses. This polls for it instead.
            #
            # Streamlit nudges toward st.iframe as the replacement here, but
            # that only takes a `src` URL, not raw HTML/JS content -- not a
            # substitute for what this actually needs.
            components.html(
                """
                <script>
                (function () {
                    let tries = 0;
                    const tryScroll = () => {
                        const el = window.parent.document.getElementById("queue-section");
                        if (el) {
                            el.scrollIntoView({behavior: "smooth", block: "start"});
                        } else if (tries++ < 30) {
                            setTimeout(tryScroll, 100);
                        }
                    };
                    tryScroll();
                })();
                </script>
                """,
                height=0,
            )
        with st.container(key="queue_card"):
            queue_view = st.segmented_control(
                "Queue view", ["Escalated to human", "Auto-resolved"],
                key="queue_view", label_visibility="collapsed",
            )
            if queue_view == "Auto-resolved":
                render_auto_resolved_table(filtered_records)
            else:
                render_queue_table(filtered_records)

    with tab_technical:
        st.markdown(
            '<p class="section-caption">Agent-level detail, kept separate from the business-facing view '
            "(spec Section 10).</p>",
            unsafe_allow_html=True,
        )
        render_agent_legend()
        left, right = st.columns(2)
        with left:
            st.plotly_chart(chart_confidence_distribution(filtered_records), width='stretch')
        with right:
            st.plotly_chart(chart_tool_use_frequency(filtered_records), width='stretch')

